// Write src/kernelCode.ts from the files in whybook/server/kernel_code.
//
// The frontend sends this code to the kernel. Keeping it in the bundle lets
// the view list variables without the server extension, as in JupyterLite.
// The Python files sit at the top of the folder. Another language has a
// folder of its own, and its exports start with the folder's name:
// r/inspect_variables.R becomes rInspectVariables. Each language also gets
// a map from the file's name to its code, `python` and `r`, which its
// adapter in src/model/languages.ts reads.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';

const source = 'whybook/server/kernel_code';
const lines = [
  '// Generated by scripts/embed-kernel-code.mjs from whybook/server/kernel_code.',
  '// Edit the files there and run `jlpm build:kernel-code` instead.',
  ''
];
const camel = text =>
  text.replace(/_([a-z])/g, (_, letter) => letter.toUpperCase());
// Embeds the files of one language, and the map of that language.
const embed = (language, prefix, folder, files) => {
  const names = [];
  for (const file of files) {
    const name = file.replace(/\.[^.]+$/, '');
    const code = readFileSync(`${folder}/${file}`, 'utf8');
    lines.push(
      `export const ${camel(prefix + name)} = ${JSON.stringify(code)};`,
      ''
    );
    names.push(`  ${name}: ${camel(prefix + name)}`);
  }
  lines.push(
    `export const ${language}: Record<string, string> = {`,
    names.join(',\n'),
    '};',
    ''
  );
};
const entries = readdirSync(source).sort();
embed(
  'python',
  '',
  source,
  entries.filter(file => file.endsWith('.py'))
);
for (const folder of entries) {
  if (
    /^[a-z]+$/.test(folder) &&
    statSync(`${source}/${folder}`).isDirectory()
  ) {
    embed(
      folder,
      `${folder}_`,
      `${source}/${folder}`,
      readdirSync(`${source}/${folder}`).sort()
    );
  }
}
writeFileSync('src/kernelCode.ts', lines.join('\n'));
